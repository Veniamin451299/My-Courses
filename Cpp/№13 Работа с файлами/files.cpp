#include <iostream>
#include <string>
#include <fstream> // Библиотека для работы с файлами

using namespace std;

int main() {
	setlocale(LC_ALL, ".UTF-8");

	// Для работы с файлами будем создавать или открывать, редактировать файл через библиотеку fstream

	// Для начало разбёрем открытие/создание файла и его запись (Через класс ofstream "output file")
	ofstream outfile("text.txt", ios_base::out); /*Создаём или открываем объект по имени text.txt и формату открытия файла ios_base::out*/
	if(outfile.is_open()) {	// Проверяем открыт ли файл для записи по методу is_open()
		outfile << "Hello World!";		// Записываем данные
		outfile.close();	// обязательно в конце закрываем файл, чтобы не перегружать память компьютера из-за постоянного открытого файла!
	}

	// Теперь разберём чтение файла (Через класс ifstream "input file") 
	ifstream infile("text.txt");	// Обращаемся к файлу и открываем его (Без каких-либо форматов!!!)
	if(infile.is_open()) {
		// string temp; Рабочая переменная для чтения
		// infile >> temp; - такая бы запись раньше просто записала бы одно слово из файла в переменную и всё. Прописывалось подобно cin >> temp
		// Иной способ:
		char *temp = new char; // Рабочий массив для чтения
		infile.getline(temp, 100);	// Метод для получения символов. Записывая в массив temp до 100 символов из файла 
		cout << temp << endl;
		infile.close();		// тоже обязательно закрываем файл!
	}


	return 0;
}

