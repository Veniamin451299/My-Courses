#include <iostream>

using namespace std;

int main() {
	setlocale(LC_ALL, ".UTF-8");
	void Minimum(int *arr, int len); // скелет функции из практики

	// *, & -- амперсанды для указателя, ссылки


	/* Ссылка -- принимает адрес ячейки памяти переменной или массива из оперативной памяти компьютера. 
	Занимает значительно меньше памяти при создании, чем перменная т.к. не хранит значение, а лишь адрес. */
	int num = 10;	// Переменная - 4 байт
	int &a = num;	// Ссылка (Занимает намного меньше памяти) - принимает ссылку на адрес памяти переменной num

	cout << "Адрес переменной: " << &num << " Значение переменной: " << num << endl;
	cout << "Адрес ссылки: " << &a << " Значение ссылки по адресу: " << a << endl;
	cout << endl;

	/* Можно перезаписать значение переменной по её адресу обращаясь через ссылку */
	int num2 = 20;
	int &b = num2;
	cout << "Значение ссылки по адресу: " << b << " Значение переменной: " << num2 << endl;

	b = 15;
	cout << "Новое значение ссылки по адресу: " << b << " Новое значение переменной: " << num2 << endl;
	cout << endl;



	/* Указатель -- указывает на адрес переменной/массива
	В отличиие от ссылок может быть пустым, очищаем и удаляем, более функционален */

	int num3 = 50;

	int *ptrnum3; // Пуст
	ptrnum3 = &num3; // Принимает адрес переменной
	cout << "Адрес переменной: " << &num3 << " Значение переменной: " << num3 << endl;
	cout << "Адрес указателя: " << ptrnum3 << " Значение адреса указателя: " << *ptrnum3 << endl;
	cout << endl;

	// Можно менять значения по адресу через указатель как и ссылки
	*ptrnum3 = 25; // ставим амперсанд "*" перед указателем, т.к. обращаемся ко значению переменной num3 по адресу
	cout << "Адрес переменной: " << &num3 << " Значение переменной: " << num3 << endl;
	cout << "Адрес указателя: " << ptrnum3 << " Значение адреса указателя: " << *ptrnum3 << endl;
	cout << endl;

	// Очситка указателя
	ptrnum3 = nullptr; 	// очищаем указатель
	cout << "Адрес указателя: " << ptrnum3 << " Значение адреса указателя: " << "*ptrnum3 - ничего не выведет" << endl; 
	// значения пустого указетеля имеют нулевой адрес и значение адреса
	cout << endl;



	// ПРАКТИЧЕСКИЙ ПРИМЕР "Поиск минимального числа"
	int arr[] = {5, 7, 3, -2, 5}; // Массив данных
	Minimum(arr, 5); // Вызов функции, передаём массив и размер массива в качестве параметров

	return 0;
}

// ФУНКЦИЯ ПРАКТИЧЕСКОГО ПРИМЕРА
void Minimum(int *arr, int len) { // В параметр берём указатель на 1-й элемент массива arr, а также, берём длину данного массива
	
	int min = *arr;		// разыменовываем указатель в рабочую переменную

	for(int i = 0; i < len; i++) {	// создаём цикл для обхода по массиву
		if(min > *(arr + i))	/* Здесь мы к указателю прибавляем порядковый номер элемента массива, чтобы указать на него 
		(ВЕДЬ К УКАЗАТЕЛЯМ МОЖНО КАК ПРИБАВЛЯТЬ, ТАК И ОТНИМАТЬ КОЛИЧЕСТВО СДВИГОВ ПО ЯЧЕЙКЕ ПАМЯТИ КАКОЙ-ЛИБО ИЗ СТРУКТУР ДАННЫХ) */
			min = *(arr + i); 
	}
	cout << "Минимальное значение: " << min << endl; 
}