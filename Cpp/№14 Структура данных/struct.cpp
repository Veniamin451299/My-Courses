#include <iostream>
#include <string>

using namespace std;

// Структуры нужны для работы с разными объектами имеющие какие-нибудь общие характерстики - общую структуру

	struct Point {		// Так же мы можем создать структуру, характеристики которой может унаследовать ещё другая структура, да бы не загромождать другую эту структуру 
		int x, y;
	};

	struct Tree { 	// создаётся структура вне главной функции программы
		string name;	// Создаём общие харакеристики структуры, которые могут иметь разные объекты (в примере, разные виды деревьев)
		int age;
		bool is_alive;
		float height;
		Point place; 	// Наследуем все характеристики новой структуры в старую

		// Так же мы можем передавать в качестве характеристик структры и функции
		void get_info() {
			cout << "Название дерева: " << name << "\nВозраст дерева: " << age << endl; 	// и остальные характеристики структуры 
			cout << endl;
		}
	}; // обязательно здесь уже ставим ;

int main() {
	setlocale(LC_ALL, ".UTF-8");

	Tree dub;		// Создание объекта на основе структуры Tree
	dub.name = "Дуб";	// Подключаем пареметры (характеристики) структуры к объекту
	dub.age = 24;
	dub.place.x = 500; // обращаемся теперь к характеристикам новой структуры через старую
	dub.place.y = 400;

	Tree elka;
	elka.name = "Елка";
	elka.age = 5;
	elka.place.x = 150;
	elka.place.y = 200;

	cout << dub.name << " - " << dub.age << endl; 
	cout << elka.name << " - " << elka.age << endl;
	cout << endl;

	cout << "Результат применения функций к объектам:" << endl;
	dub.get_info();
	elka.get_info();

	return 0;
}

