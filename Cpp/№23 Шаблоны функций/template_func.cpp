#include <iostream>
#include <string>


using namespace std;

/* Шаблоны функций - это такая функция, в которую можно передать не только парметры, но и тот тип данных, который будет использоваться внутри самой функции
 */

template <typename T>	/* Создаём шаблон указывая какие дополнительные параметры мы будем получать в этой шаблонной функции. В нашем случае мы будем получать
только один тип данных.
Так же в шаблоны можно создавать не только один парметр, но и несколько (typename T1, typename T2), если это нужно в разных местах программы. */
void print_arr(T* arr, int len) {	// Теперь в нашей шаблонной функции указываем вместо старого типа данных "int", наш шаблонный тип данных "T"
	for(int i = 0; i < len; i++) {	// Пробег по массиву
		cout << *(arr + i) << " ";
	}
	cout << endl;
}

int main() {
	setlocale(LC_ALL, ".UTF-8");

	int arr1[] = {5, 3, 6, 2, 0, -4};
	print_arr<int>(arr1, 6);	/* Теперь при вызове функции лучше указывать в <> нужный нам тип данных, хоть иногда программа сама автоматически может определять
	тип данных и подставлять, но во избежания конфликтов и ошибок будем прописывать их */

	float arr2[] = {3.4f, 5.24f, 2.5f};
	print_arr<float>(arr2, 3);

	return 0;
}