#include <iostream>
#include <string>


using namespace std;

/* Классы - уквально те же структуры данных, однако на основе структур мы могли бы создавать малые объекты, а на основании Классов -- большие объекты.
Либо, класс - это абстракция описывающая методы, свойства, ещё не существующих объектов. Объекты — конкретное представление абстракции, имеющее свои 
свойства и методы. Созданные объекты на основе одного класса называются экземплярами этого класса. Эти объекты могут иметь различное поведение, 
свойства, но все равно будут являться объектами одного класса. */

class Building {
private:		// Модификатор доступа (public, private, protected)
	int year;	// Поля класса - переменные в классах
	string type;

public:
	void set_obj(int y, string t) {		// так как мы соблюдаем правила инкапсуляции, создаём метод для инициализации данных для полец
		year = y;
		type = t;
	}

	void get_info() {		// Метод класса - функции в классах
		cout << "Тип здания " << type << "\nГод постройки " << year << endl; // Поля и методы независимо от модификатора доступа будут видны и открыты для работы в самом классе
		cout << endl;
	}
};

int main() {
	setlocale(LC_ALL, ".UTF-8");

	Building school;
	// school.type = "Школа"; инициализация, будь поля в публичном доступе пользования
	// school.yaer = 2000;
	school.set_obj(2000, "Школа");
	school.get_info();
	
	Building house;
	house.set_obj(2010, "Дом");
	house.get_info();
	
	return 0;
}

/* Модификаторы достуа (public, private, protected) - это процесс "инкапсуляции", который позволяет на задать доступ к полям и методам класса.
Public - доступ открытый, в нём данные класса незащещаны и открыты в не доступа класса.
Private - доступ закрытый, в нём данные класса защещаны и видны лишь в зоне области самого класса, но не за пределах его. 
Protected - доступ защищающий, в нём данные класа защещаны и видны в зоне области самого класса и в классах "наследниках" 

ВАЖНЫЙ НЮАНС! В ООП принято в классах поля хранить в private! Таково правило инкапсуляции, что все поля класса должны быть закрыты отпрямого доступа к ним. */
