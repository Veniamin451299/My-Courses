#include <iostream>
#include <string>


using namespace std;

/* Наслодование - это когда созданы 2 класса и мы указываем, что один из них "Родитель", другой "Наследник". В таком случае, класс "родитель" может описывать
какой-нибудь общий, базовый функционал, а "наследник" может наследовать весь этот базовый функционал и дополнять ещё и своим личным функционалом.
 */

class PC {		// Класс "Родитель"
private:
	int diagonal;
	string os;
public:
	PC(int diagonal, string os) {
		this->diagonal = diagonal;
		this->os = os;
	}

	void get_info() {			// Представим, что в классе родителе мы добавили новый метод, как нам теперь его дополнить в классе наследнике?
		cout << "OS: " << os << ". Diagonal: " << diagonal << endl;
	}
};

class Laptop: public PC {		// Класс "Наследник" (наследуем через ":" функционал класса родителя по модиф. доступа public)
private:
	float weight;
public:
	// Чтобы обращаться к параметрам конструктора класса "родителя", нужно прописать и конструктор самого "родителя" с нужными параметрами:
	Laptop(int diagonal, string os, float weight): PC(diagonal, os) {	// Здесь через ":" мы обратились к конструктору родителя и объявили его параметры
		this->weight = weight;											// И теперь параметры родителя из laptop будут переданы в конструктор самого класса родителя 
	}
	/* А чтобы дополнить новый метод из класса родителя. Мы создаём этот же такой же метод в классе наследнике, однако первым делом мы его вызывем из класса родителя, 
	чтобы тот сработал полностью так, как он идёт там. А по заввершению алгоритма метода класса родителя, мы приписываем новый функционал для этого же метода в 
	наследнике, который последует дальше. Пример: */
	void get_info() {	// Создаём такой же метод
		PC::get_info();	// Далее вызываем из класса родителя PC через "::" метод get_info
		cout << "Weight: " << weight << endl; 	// Теперь добавляем новый функционал к методу родителя!
	}
};

int main() {
	setlocale(LC_ALL, ".UTF-8");

	Laptop mac(16, "Mac", 1.5f);
	mac.get_info();
	
	return 0;
}

/* А теперь важный момент!!! Поговорим про модификатор доступа protected. Он полезен как раз-таки в наследовании, потому что предоставляет доступ к данным классов
как "родителя", так и класса "наследника". */

class Parent {
protected:
	string name;
	int age;
public:
	Parent(string name, int age) {
		this->name = name;
		this->age = age;
	}
};

class Daughter: public Parent {	// Наследуем от класса родителя
protected:
	string hair;
public:
	Daughter(string name, int age, string hair): Parent(name, age) { 
		this->name = name;	// теперь можно увидеть, что мы можем обращаться к параметрам класса родителя и менять их даже в классе наследнике
		this->age = 16;
		this->hair = hair;
	}
};