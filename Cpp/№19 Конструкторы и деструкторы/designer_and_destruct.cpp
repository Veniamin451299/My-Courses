#include <iostream>
#include <string>


using namespace std;

/* Конструктор - по-сути тот же метод/функция, разница лишь в том, что конструкторы вызываются автоматически при создании какого-либо объекта на основе 
определённого класса. 

Деструкторы - противоположность конструкторам. Они вызываются по уничтожению объектов. Объекты же уничтожаются по завершении программы. Удобно к примеру,
когда надо закрыть файл, закрыть базу данных по завершению прогаммы. Обязятельное выполнение какого-либо действия перед уничтожением объекта.

Ключевое слово this (указатель this) - позволяет нам обратиться к каким-либо вещам, что описаны внутри самого класса. 
К примеру у нас есть метод, названия параметров которых совпадает с названиями полей класса. И дабы компилятор понимал к чему обращаться мы указателеме this
помечаем объекты класса, т.е. поля. Применять указатель this можно и к методам, если есть конфликт имён методов!
*/

class Building {
private:		
	int year;	
	string type;

public:
	Building(int year, string type) {		// Конструктор обязательно называем именем самого класса
		this->year = year;	// Здесь мы используем указатель this, чтобы пометить, при одинаковых имён параметров конструктора/метода и полей класса, где мы 
		this->type = type;	// обращаемся к полям.
	}

	Building() {} 		// Мы так же можем делать перегрузку конструктора

	void get_info() {
		cout << "Тип здания " << type << "\nГод постройки " << year << endl;
		cout << endl;
	}

	~Building() {		// Для создания деструктора пишем то же имя класса, но перед ставим символ тильды ~. Параметры обычно мы не передаём в деструктор
		cout << "Delete object!" << endl; // А раз параметры не задаём, поэтому описываем только тело деструктора!
	}
};

int main() {
	setlocale(LC_ALL, ".UTF-8");

	Building school(2000, "Школа");	// Теперь создавая объект мы вызываем конструктор, к которому нужно обязательно теперь присвоить значения для его полей
	school.get_info();
	
	Building house(2010, "Дом");
	house.get_info();

	Building church;	// Т.к. мы выполнил перегрузку коструктора, компилятор выбрал второй вариант конструктора из класса
	church.get_info();
	
	return 0;
}
